import os
import json
import random
import shutil
from PIL import Image

# 1. Set the dataset locations
source_dir = "/content/industrial_dataset"
annotation_file = os.path.join(source_dir, "info.labels")
output_dir = "/content/yolo_dataset"

# 2. Read annotations
with open(annotation_file, "r", encoding="utf-8") as f:
    data = json.load(f)

# 3. Define the four classes
class_names = ["blue", "green", "red", "yellow"]
class_to_id = {
    name: index for index, name in enumerate(class_names)
}

# 4. Create fresh output folders
if os.path.exists(output_dir):
    shutil.rmtree(output_dir)

for split in ["train", "val", "test"]:
    os.makedirs(os.path.join(output_dir, "images", split), exist_ok=True)
    os.makedirs(os.path.join(output_dir, "labels", split), exist_ok=True)

# 5. Keep only images that have actual bounding-box annotations
annotated_items = [
    item for item in data["files"]
    if item.get("boundingBoxes")
]

# 6. Split annotated images into training, validation, and testing
random.seed(42)
random.shuffle(annotated_items)

total = len(annotated_items)
train_end = int(total * 0.70)
val_end = int(total * 0.85)

splits = {
    "train": annotated_items[:train_end],
    "val": annotated_items[train_end:val_end],
    "test": annotated_items[val_end:]
}

# 7. Convert bounding boxes into YOLO format
for split_name, items in splits.items():

    for index, item in enumerate(items):

        image_path = os.path.join(source_dir, item["path"])

        if not os.path.isfile(image_path):
            print("Skipping missing image:", image_path)
            continue

        # Read image size
        with Image.open(image_path) as img:
            image_width, image_height = img.size

        # Use a unique filename for each copied image
        new_name = f"{split_name}_{index:04d}.jpg"

        # Convert image to JPEG RGB format
        with Image.open(image_path) as img:
            img.convert("RGB").save(
                os.path.join(output_dir, "images", split_name, new_name),
                quality=95
            )

        label_path = os.path.join(
            output_dir,
            "labels",
            split_name,
            os.path.splitext(new_name)[0] + ".txt"
        )

        with open(label_path, "w", encoding="utf-8") as label_file:

            for box in item["boundingBoxes"]:

                class_name = box["label"]

                if class_name not in class_to_id:
                    continue

                x = float(box["x"])
                y = float(box["y"])
                width = float(box["width"])
                height = float(box["height"])

                # YOLO needs normalized center coordinates
                x_center = (x + width / 2) / image_width
                y_center = (y + height / 2) / image_height
                norm_width = width / image_width
                norm_height = height / image_height

                class_id = class_to_id[class_name]

                label_file.write(
                    f"{class_id} "
                    f"{x_center:.6f} "
                    f"{y_center:.6f} "
                    f"{norm_width:.6f} "
                    f"{norm_height:.6f}\n"
                )

# 8. Create the YOLO configuration file
yaml_path = os.path.join(output_dir, "data.yaml")

with open(yaml_path, "w", encoding="utf-8") as f:
    f.write(f"path: {output_dir}\n")
    f.write("train: images/train\n")
    f.write("val: images/val\n")
    f.write("test: images/test\n")
    f.write("names:\n")

    for class_id, class_name in enumerate(class_names):
        f.write(f"  {class_id}: {class_name}\n")

# 9. Display the results
print("Dataset preparation complete!")
print("\nImages and labels created:")

for split_name in ["train", "val", "test"]:
    image_folder = os.path.join(output_dir, "images", split_name)
    label_folder = os.path.join(output_dir, "labels", split_name)

    image_count = len(os.listdir(image_folder))
    label_count = len(os.listdir(label_folder))

    print(
        f"{split_name}: {image_count} images, "
        f"{label_count} label files"
    )

print("\nYOLO configuration saved to:", yaml_path)
print("Class mapping:", class_to_id)

