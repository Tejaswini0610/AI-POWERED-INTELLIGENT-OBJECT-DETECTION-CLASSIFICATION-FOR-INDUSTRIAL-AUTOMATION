import os
import json
from PIL import Image
from collections import Counter

dataset_path = "/content/industrial_dataset"
json_path = os.path.join(dataset_path, "info.labels")

# Read annotation information
with open(json_path, "r", encoding="utf-8") as f:
    annotations = json.load(f)

class_counts = Counter()
total_boxes = 0
valid_boxes = 0
invalid_boxes = 0
images_with_boxes = 0
empty_annotations = 0
missing_files = 0

for item in annotations.get("files", []):

    # Find the image
    image_path = os.path.join(dataset_path, item["path"])

    if not os.path.exists(image_path):
        print("Image not found:", item["path"])
        missing_files += 1
        continue

    # Read image dimensions
    with Image.open(image_path) as img:
        image_width, image_height = img.size

    boxes = item.get("boundingBoxes", [])

    if boxes:
        images_with_boxes += 1
    else:
        empty_annotations += 1

    for box in boxes:
        total_boxes += 1

        label = box.get("label")
        x = box.get("x", 0)
        y = box.get("y", 0)
        width = box.get("width", 0)
        height = box.get("height", 0)

        class_counts[label] += 1

        # Check whether the box has valid dimensions
        if (
            width > 0
            and height > 0
            and x >= 0
            and y >= 0
            and x + width <= image_width
            and y + height <= image_height
        ):
            valid_boxes += 1
        else:
            invalid_boxes += 1
            print(
                "Check box:", os.path.basename(image_path),
                "Image size:", image_width, "x", image_height,
                "Box:", box
            )

